import Foundation

func require(_ value: @autoclosure () -> Bool, _ message: String) { if !value() { fatalError(message) } }
func rejected(_ action: () throws -> Void, _ message: String) { do { try action(); fatalError(message) } catch {} }
let fm = FileManager.default
let root = URL(fileURLWithPath: "/private/tmp/OpenCommander-TreeTests-\(UUID().uuidString)", isDirectory: true)
try fm.createDirectory(at: root, withIntermediateDirectories: false)
defer { try? fm.removeItem(at: root) }
let source = root.appendingPathComponent("Quelle")
try fm.createDirectory(at: source.appendingPathComponent("Unterordner"), withIntermediateDirectories: true)
let bytes = Data(repeating: 23, count: 3 * 1024 * 1024)
try bytes.write(to: source.appendingPathComponent("Unterordner/Grüsse.bin"))
try Data("versteckt".utf8).write(to: source.appendingPathComponent(".hidden"))
try fm.createSymbolicLink(atPath: source.appendingPathComponent("link").path, withDestinationPath: "/does/not/exist")
let destination = root.appendingPathComponent("Ziel")
let stage = try DurableTreeTransfer.create(source: source, destination: destination, move: false, replace: false)
var transferred: Int64 = 0
let paused = try DurableTreeTransfer.resume(stage, control: { transferred >= 1024 * 1024 ? .pause : .proceed }, progress: { copied, _ in transferred = copied })
require(paused.state == .paused, "tree did not pause")
require(!SafeFileOperations.exists(destination), "partial tree published")
var activities: [DurableFileCopy.Activity] = []
let completed = try DurableTreeTransfer.resume(stage, activity: { activities.append($0) })
require(completed.state == .completed, "tree resume failed")
let content = try Data(contentsOf: destination.appendingPathComponent("Unterordner/Grüsse.bin"))
require(content == bytes, "tree contents wrong")
let link = try fm.destinationOfSymbolicLink(atPath: destination.appendingPathComponent("link").path)
require(link == "/does/not/exist", "link followed or changed")
let visible = try fm.contentsOfDirectory(atPath: destination.path)
require(!visible.contains(where: { $0.hasPrefix(".OpenCommanderTransfer-") }), "private journals published")
let nested = try fm.contentsOfDirectory(atPath: destination.appendingPathComponent("Unterordner").path)
require(nested.count == 1, "child journal leaked")
require(activities.contains { $0.phase == .verifying && $0.done == $0.total && $0.total > 0 }, "whole tree hashing reports verified bytes")
require(activities.contains { $0.phase == .checkingPartial && $0.total > 0 }, "tree forwards unfinished-file verification progress")
require(activities.contains { $0.phase == .publishing }, "tree publication phase missing")
print("PASS directory/source verification byte counts and resumed child-file checking are separate from copying")
print("PASS Unicode/hidden/link directory copy, mid-file pause/resume and no published child journals")

let priorityTarget = root.appendingPathComponent("priority")
let priorityStage = try DurableTreeTransfer.create(source: source, destination: priorityTarget, move: false, replace: false)
var checkpoint: Int64 = 0
let priorityPause = try DurableTreeTransfer.resume(priorityStage, control: { checkpoint >= 1024 * 1024 ? .pause : .proceed }, progress: { value, _ in checkpoint = value })
require(priorityPause.state == .paused, "priority fixture did not pause")
let hiddenOutput = priorityStage.appendingPathComponent("payload/.hidden")
try Data("corrupt!".utf8).write(to: hiddenOutput)
var resumedProgress: [Int64] = []
rejected({ _ = try DurableTreeTransfer.resume(priorityStage, progress: { bytes, _ in resumedProgress.append(bytes) }) }, "changed completed output accepted")
let priorityJournal = try JSONDecoder().decode(DurableTreeTransfer.Journal.self, from: Data(contentsOf: priorityStage.appendingPathComponent("root.json")))
require(priorityJournal.entries.first { $0.path.hasSuffix("Grüsse.bin") }?.output != nil, "unfinished file was not continued before checking completed output")
require(resumedProgress.allSatisfy { $0 >= checkpoint }, "resume lost displayed checkpoint bytes")
require(!SafeFileOperations.exists(priorityTarget), "corrupt tree published")
print("PASS unfinished-file-first resume preserves progress and still refuses changed completed data before publication")

let oldTarget = root.appendingPathComponent("replace")
let old = Data("alte Datei".utf8); try old.write(to: oldTarget)
let replacement = try DurableTreeTransfer.create(source: source, destination: oldTarget, move: false, replace: true)
rejected({ _ = try DurableTreeTransfer.resume(replacement, publish: { _, _ in throw CocoaError(.fileWriteUnknown) }) }, "injected publication failure ignored")
let retained = try Data(contentsOf: oldTarget)
require(retained == old, "failed replacement did not restore old destination")
let replaced = try DurableTreeTransfer.resume(replacement)
require(replaced.state == .completed && replaced.backup != nil, "replacement retry failed")
let undoCopy = FileUndoRecord(source: source, destination: oldTarget, replacedBackup: replaced.backup)
try undoCopy.undo(move: false)
let restored = try Data(contentsOf: oldTarget)
require(restored == old, "replacement undo failed")
print("PASS failed replacement restores old data; retry and Undo restore previous destination")

let moveTarget = root.appendingPathComponent("move")
let moveStage = try DurableTreeTransfer.create(source: source, destination: moveTarget, move: true, replace: false)
let moved = try DurableTreeTransfer.resume(moveStage)
require(moved.state == .completed && !SafeFileOperations.exists(source), "source not moved")
require(moved.quarantine != nil && SafeFileOperations.exists(moved.quarantine!), "original source not retained")
let undoMove = FileUndoRecord(source: source, destination: moveTarget, replacedBackup: nil, quarantinedSource: moved.quarantine)
try undoMove.undo(move: true)
require(SafeFileOperations.exists(source) && !SafeFileOperations.exists(moveTarget), "move undo failed")
let returned = try Data(contentsOf: source.appendingPathComponent("Unterordner/Grüsse.bin"))
require(returned == bytes, "original source bytes not restored")
print("PASS phased directory move retains original until publication; Undo restores original source")

let racingSource = root.appendingPathComponent("racing-source")
let racingTarget = root.appendingPathComponent("racing-target")
try Data("source at start".utf8).write(to: racingSource)
try Data("old destination".utf8).write(to: racingTarget)
let racingStage = try DurableTreeTransfer.create(source: racingSource, destination: racingTarget, move: true, replace: true)
rejected({ _ = try DurableTreeTransfer.resume(racingStage, publish: { from, to in
    try fm.moveItem(at: from, to: to)
    try Data("externally changed source".utf8).write(to: racingSource)
}) }, "post-publication source change accepted as move success")
let racingOld = try Data(contentsOf: racingTarget), racingOriginal = try Data(contentsOf: racingSource)
require(racingOld == Data("old destination".utf8) && racingOriginal == Data("externally changed source".utf8), "failed move lost old target or changed source")
let racingPayload = try Data(contentsOf: racingStage.appendingPathComponent("payload"))
require(racingPayload == Data("source at start".utf8), "failed move did not retain copied payload")
rejected({ _ = try DurableTreeTransfer.resume(racingStage) }, "changed source resumed after rollback")
let racingRetry = try Data(contentsOf: racingTarget)
require(racingRetry == racingOld, "retry changed restored old target")
print("PASS post-publication source mutation rolls destination back, retaining changed source and copied payload")

let changedTarget = root.appendingPathComponent("changed")
let changedStage = try DurableTreeTransfer.create(source: source, destination: changedTarget, move: false, replace: false)
try Data("changed".utf8).write(to: source.appendingPathComponent(".hidden"))
rejected({ _ = try DurableTreeTransfer.resume(changedStage) }, "changed tree source accepted")
require(!SafeFileOperations.exists(changedTarget), "changed source published")
rejected({ _ = try DurableTreeTransfer.create(source: source, destination: source.appendingPathComponent("nested"), move: true, replace: false) }, "move inside source accepted")
print("PASS changed source and destination-inside-source refused without publication")
